# Windows (PowerShell) version of scripts/up.sh: run the whole product on one machine.
# Usage (from the repository folder):   powershell -ExecutionPolicy Bypass -File scripts\up.ps1 -Demo
#   -Demo    also load demo shops and conversations
#   -Down    stop everything
#   -Reset   stop and DELETE the database volume
param([switch]$Demo, [switch]$Down, [switch]$Reset)
$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..\deploy')
$envFile = '.env'

function Gen([int]$n = 32) {
  $bytes = New-Object byte[] 48
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  (([Convert]::ToBase64String($bytes)) -replace '[/+=]', '').Substring(0, $n)
}

if ($Down)  { docker compose down; exit 0 }
if ($Reset) { docker compose --profile demo --profile redis down -v; Remove-Item -Force -ErrorAction SilentlyContinue $envFile; Write-Host 'reset'; exit 0 }

# Windows git often checks files out with CRLF line endings. Files that run inside Linux containers must have LF,
# or the database's first-start script fails silently and no roles are created. Normalise them (safe to repeat).
foreach ($f in @('postgres-init\10-roles.sh', '..\db\bootstrap_roles.sql', '..\frontend\deploy\Caddyfile', '..\frontend\deploy\entrypoint.sh')) {
  if (Test-Path $f) {
    $t = [IO.File]::ReadAllText((Resolve-Path $f))
    if ($t.Contains("`r`n")) { [IO.File]::WriteAllText((Resolve-Path $f), $t.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false))); Write-Host "fixed line endings: $f" }
  }
}

function PortFree([int]$p) { try { $l = [Net.Sockets.TcpListener]::new([Net.IPAddress]::Any, $p); $l.Start(); $l.Stop(); $true } catch { $false } }

if (-not (Test-Path $envFile)) {
  $port = (8080, 8081, 8090, 8181, 8888, 9080 | Where-Object { PortFree $_ } | Select-Object -First 1)
  if (-not $port) { $port = 8080 }
  $key = New-Object byte[] 32
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($key)
  $lines = @(
    '# Generated by scripts/up.ps1. Demo mode: simulated WhatsApp network + deterministic local AI stand-in.',
    'APP_ENV=staging',
    "POSTGRES_PASSWORD=$(Gen)", "APP_OWNER_PASSWORD=$(Gen)", "APP_USER_PASSWORD=$(Gen)", "APP_PRICING_PASSWORD=$(Gen)", "APP_SYSTEM_PASSWORD=$(Gen)",
    "MASTER_KEY=$([Convert]::ToBase64String($key))",
    "JWT_SECRET=$(Gen 48)", "OTP_SECRET=$(Gen 48)", "META_APP_SECRET=$(Gen)", "META_VERIFY_TOKEN=$(Gen 24)",
    'SIMULATOR_ENABLED=true', 'LLM_PROVIDER=local', 'OTP_ACCEPT_ANY=true', 'PAYMENT_PROVIDER=test',
    'OTP_MIN_INTERVAL_S=1', 'OTP_PER_PHONE_PER_HOUR=500', 'OTP_PER_IP_PER_HOUR=2000', "WEB_PORT=$port"
  )
  # UTF-8 without a byte-order mark, LF line endings (docker compose is strict about both)
  [IO.File]::WriteAllText((Join-Path (Get-Location) $envFile), ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding($false)))
  Write-Host 'created deploy\.env with fresh secrets'
}

$ErrorActionPreference = 'Continue'      # from here on we check docker's exit code ourselves, so a docker message is not turned into a crash
# ---- start-up with a visible story: every step prints what it is doing, and a failure prints what to do next ----
$env:BUILDKIT_PROGRESS = 'plain'; $env:COMPOSE_PROGRESS = 'plain'      # show each download/build step instead of a silent spinner
$web = ((Get-Content $envFile | Where-Object { $_ -like 'WEB_PORT=*' }) -replace 'WEB_PORT=', '').Trim()
function Step([string]$n, [string]$m) { Write-Host ''; Write-Host "[$n] $m" -ForegroundColor Cyan }
function Fail([string]$m) {
  Write-Host ''; Write-Host "FAILED: $m" -ForegroundColor Red
  Write-Host '--- containers ---'; docker compose ps -a
  Write-Host '--- last log lines (send these to your engineer) ---'; docker compose logs --tail 40
  exit 1
}

Step '1/4' 'Checking Docker is running'
docker info *> $null
if ($LASTEXITCODE -ne 0) { Fail 'Docker is not running. Open Docker Desktop, wait until it says "running", then run this again.' }
Write-Host 'Docker is running.'

Step '2/4' 'Downloading and building everything (first run takes 5-15 minutes; lines below are progress, not errors)'
docker compose up -d --build
if ($LASTEXITCODE -ne 0) { Fail 'Docker could not build or start the services (see the lines above; "no space left" means free about 10 GB).' }

Step '3/4' 'Waiting for the app to answer'
$ready = $false
for ($i = 1; $i -le 60; $i++) {
  try { $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 "http://localhost:$web/api/v1/public/config"; if ($r.StatusCode -eq 200) { $ready = $true; break } } catch { }
  Write-Host "  waiting ($i/60)... services: $((docker compose ps --format '{{.Service}}={{.State}}') -join ' ')"
  Start-Sleep -Seconds 3
}
if (-not $ready) { Fail 'The app did not answer within 3 minutes.' }
Write-Host 'The app is answering.'

if ($Demo) {
  Step '4/4' 'Loading the demo shops and conversations (about a minute)'
  docker compose --profile demo run --rm seed
  if ($LASTEXITCODE -ne 0) { Fail 'Loading the demo data failed (the app itself is running).' }
} else { Step '4/4' 'Skipping demo data (add -Demo to load it)' }

Write-Host ''
Write-Host 'READY' -ForegroundColor Green
Write-Host "  Open  http://localhost:$web      (the product is at http://localhost:$web/app)"
Write-Host '  Sign in as the owner +91 99999 00001 (the login code fills in by itself), operator +91 99999 00000.'
Write-Host '  Any new mobile number signs up with any 6-digit code.'
Write-Host '  Live logs:  cd deploy ; docker compose logs -f --tail 20        Stop:  scripts\up.ps1 -Down'
